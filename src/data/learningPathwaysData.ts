/**
 * Returns all ancestor prerequisite node IDs (direct and indirect)
 */
export function getAncestorPrerequisites(nodeId: string, allNodes: PathwayNode[]): Set<string> {
  const nodeMap = new Map(allNodes.map((n) => [n.id, n]));
  const ancestors = new Set<string>();

  function traverse(currentId: string) {
    const node = nodeMap.get(currentId);
    if (!node) return;
    for (const prereqId of node.prerequisites) {
      if (!ancestors.has(prereqId)) {
        ancestors.add(prereqId);
        traverse(prereqId);
      }
    }
  }

  traverse(nodeId);
  return ancestors;
}

/**
 * Returns all descendant nodes that require this node (direct and indirect)
 */
export function getDescendantDependents(nodeId: string, allNodes: PathwayNode[]): Set<string> {
  const dependents = new Set<string>();

  function traverse(currentId: string) {
    for (const node of allNodes) {
      if (node.prerequisites.includes(currentId) && !dependents.has(node.id)) {
        dependents.add(node.id);
        traverse(node.id);
      }
    }
  }

  traverse(nodeId);
  return dependents;
}
